// Whether the installed engine still matches what the installer put there.
//
// The engine is replaced wholesale by `upgrade`, and `init` gitignores it — so an edit inside it is
// invisible to git while it exists and gone without warning afterwards. `init` and `upgrade` record a
// checksum of every file they installed; `doctor` and `upgrade` compare against that record so the
// loss is named before it happens.
//
// The record is written by the installer, so it is absent in the kit's own repository — where editing
// the engine IS the work — and every check below skips. That is the whole workspace-mode mechanism:
// structural, no runtime detection.
import { existsSync } from "node:fs";
import { join } from "node:path";
import { hashTree, readJson, writeJson } from "./fs.ts";

const MANIFEST_NAME = ".engine-integrity.json";

/** Regenerated by tooling, never authored: recording them would report drift on every build. */
const IGNORED_NAMES = new Set(["node" + "_modules", ".build", ".vite", "storybook-static", "package-lock.json", ".DS_Store", MANIFEST_NAME]);

/** Build outputs that share a name with tracked directories (`cli/dist` is the shipped CLI). */
const IGNORED_PATHS = new Set(["preview-app/dist"]);

export type EngineDrift = { modified: string[]; added: string[]; removed: string[] };

export function engineIntegrityManifestPath(engineRoot: string): string {
  return join(engineRoot, MANIFEST_NAME);
}

/** Record the installed engine. Call after the tree is in place and its components are installed. */
export function writeEngineIntegrityManifest(engineRoot: string): void {
  writeJson(engineIntegrityManifestPath(engineRoot), { version: 1, recordedAt: new Date().toISOString(), files: hashEngineTree(engineRoot) });
}

/**
 * What changed since the engine was installed. `undefined` means no manifest was ever written —
 * the kit's own repository — and callers must treat that as "not applicable", not as "clean".
 */
export function engineDrift(engineRoot: string): EngineDrift | undefined {
  const path = engineIntegrityManifestPath(engineRoot);
  if (!existsSync(path)) return undefined;
  const recorded = readJson<{ files?: Record<string, string> }>(path).files ?? {};
  const current = hashEngineTree(engineRoot);
  return {
    modified: Object.keys(recorded).filter((file) => file in current && current[file] !== recorded[file]).sort(),
    added: Object.keys(current).filter((file) => !(file in recorded)).sort(),
    removed: Object.keys(recorded).filter((file) => !(file in current)).sort(),
  };
}

export function hasEngineDrift(drift: EngineDrift | undefined): drift is EngineDrift {
  return Boolean(drift && (drift.modified.length || drift.added.length || drift.removed.length));
}

/** One line per changed file, prefixed so the kind of change reads at a glance. */
export function describeEngineDrift(drift: EngineDrift): string[] {
  return [
    ...drift.modified.map((file) => `changed: engine/${file}`),
    ...drift.added.map((file) => `added:   engine/${file}`),
    ...drift.removed.map((file) => `deleted: engine/${file}`),
  ];
}

function hashEngineTree(engineRoot: string): Record<string, string> {
  return hashTree(engineRoot, { excludedNames: IGNORED_NAMES, excludedPaths: IGNORED_PATHS });
}
